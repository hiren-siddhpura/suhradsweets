import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { availableOrderUnits, itemUnitPrice, orderLineUnitLabel } from '../js/order-units.js';
import { hasPermission, isStaff, validateProfile } from '../js/permissions.js';
import { actionLabel, activityDate, changeSummary, references } from '../js/activity-format.js';

test('order form shows trusted availability; financial locks disable edit and archive', async () => {
  const nodes = new Map(), calls = [], exports = [];
  let invoicePresent = true;
  const el = id => { if (!nodes.has(id)) nodes.set(id, { value: '', innerHTML: '', textContent: '', listeners: {}, addEventListener(type, fn) { this.listeners[type] = fn; }, querySelectorAll() { return []; }, showModal() {}, close() {} }); return nodes.get(id); };
  const order = { id: 'orderA', orderNumber: 'SS-1', customerId: 'customerA', customerSnapshot: { fullName: 'Asha' }, ownerUid: 'userA', assignedUserId: 'userA', status: 'confirmed', orderDate: '2026-10-10', lines: [{ kind: 'item', productId: 'itemA', quantityQty: 1000, unitPricePaise: 10000, lineTotalPaise: 10000, itemSnapshot: { name: 'Sweet', unitSymbol: 'kg' } }], stockDeductions: [{ itemId: 'itemA', quantityQty: 1000 }], subtotal: 10000, grandTotal: 10000 };
  const activity = [{ type: 'order.status_changed', orderNumber: 'SS-2026-000051', actorName: 'A Long Actor Name', customerName: 'A Long Customer Name', changedFields: { status: { before: 'draft', after: 'confirmed' } }, outcome: 'success', at: 1791710000000 }];
  const context = { document: { getElementById: el, addEventListener() {}, querySelector() { return null; } }, isStaff, validateProfile, hasPermission, showToast() {}, listOrders: async () => [order], listCustomers: async () => [{ id: 'customerA', fullName: 'Asha', contact: '123' }], listMasterRecords: async () => [], listOrderProducts: async (_db, type) => type === 'items' ? [{ id: 'itemA', name: 'Sweet', active: true, defaultUnitId: 'kg', defaultSellingPrice: 100 }] : [], listInvoices: async () => invoicePresent ? [{ orderId: 'orderA' }] : [], getOrderTaking: async () => true, listActivity: async () => ({ rows: activity, cursor: null, hasMore: false }), callOperation: async (_fn, name) => { calls.push(name); if (name === 'getOrderStock') return { items: [{ itemId: 'itemA', availableQty: 2500, onHandQty: 2500, reservedQty: 0, unit: 'kg', status: 'low_stock' }] }; throw new Error('Mutation not expected.'); }, downloadXlsx: async (_name, sheets) => { exports.push(sheets); } };
  const source = readFileSync(new URL('../js/order-ui.js', import.meta.url), 'utf8').replace(/^import .*;\r?\n/gm, '').replace('export function initOrderUi', 'function initOrderUi');
  vm.runInNewContext(`${source}\nthis.init = initOrderUi;`, Object.assign(context, { availableOrderUnits, itemUnitPrice, orderLineUnitLabel, actionLabel, activityDate, changeSummary, references }));
  const ui = context.init({ db: {}, functions: {}, auth: {} });
  ui.setSession({ uid: 'userA' }, { role: 'user', active: true, fullName: 'User A' });
  await el('order-refresh').listeners.click();
  el('order-new').listeners.click();
  assert.match(el('order-fields').innerHTML, /Available: 2\.5 kg/);
  assert.match(el('order-fields').innerHTML, /Sweet — ₹100\.00/);
  assert.doesNotMatch(el('order-fields').innerHTML, /On hand:|Reserved:|Low stock/);
  assert.doesNotMatch(el('order-body').innerHTML, /data-action="editOrder"/);
  assert.match(el('order-body').innerHTML, /data-action="archiveOrder"[^>]*disabled/);
  assert.match(el('order-body').innerHTML, /invoice exists/);
  assert.match(el('order-body').innerHTML, /View invoice/);
  el('order-body').listeners.click({ target: { closest: () => ({ dataset: { action: 'viewOrder', id: 'orderA' } }) } });
  assert.match(el('order-fields').innerHTML, /order-view-table/);
  assert.match(el('order-fields').innerHTML, /Subtotal/);
  assert.match(el('order-fields').innerHTML, /Total/);
  assert.match(el('order-fields').innerHTML, /Sweet/);
  assert.match(el('order-fields').innerHTML, /kg × 1/);
  assert.match(el('order-fields').innerHTML, /₹100\.00/);
  assert.match(el('order-fields').innerHTML, /<dt>Invoice<\/dt><dd>Created<\/dd>/);
  assert.match(el('order-view-actions').innerHTML, /View Invoice/);
  assert.doesNotMatch(el('order-view-actions').innerHTML, /Create Invoice|> Edit/);
  assert.equal(el('order-dialog-cancel').textContent, 'Close');
  for (let i = 0; i < 10 && !el('order-activity-body').innerHTML.includes('A Long Actor Name'); i++) await new Promise(resolve => setTimeout(resolve, 0));
  assert.match(el('order-activity-body').innerHTML, /A Long Actor Name/);
  assert.match(el('order-activity-cards').innerHTML, /SS-2026-000051/);
  assert.match(el('order-activity-cards').innerHTML, /A Long Customer Name/);
  assert.match(el('order-activity-cards').innerHTML, /Order status changed from Draft to Confirmed/);
  assert.match(el('order-activity-cards').innerHTML, /<dt>When<\/dt>|<dt>Action<\/dt>|<dt>Order<\/dt>/);
  await el('order-activity-export').listeners.click();
  assert.equal(exports[0][0][1][0].Customer, 'A Long Customer Name');
  assert.ok(calls.includes('getOrderStock'));
  invoicePresent = false;
  order.status = 'draft';
  await el('order-refresh').listeners.click();
  assert.doesNotMatch(el('order-body').innerHTML, /data-action="invoiceOrder"/);
  assert.match(el('order-body').innerHTML, /data-action="editOrder"[^>]*>Edit/);
  assert.match(el('order-body').innerHTML, /data-action="confirmOrder"[^>]*>Confirm/);
  order.status = 'confirmed';
  await el('order-refresh').listeners.click();
  assert.match(el('order-body').innerHTML, />Confirmed</);
  assert.match(el('order-body').innerHTML, /data-action="invoiceOrder"[^>]*>Create invoice/);
  el('order-body').listeners.click({ target: { closest: () => ({ dataset: { action: 'viewOrder', id: 'orderA' } }) } });
  assert.match(el('order-view-actions').innerHTML, /Create Invoice/);
  assert.doesNotMatch(el('order-view-actions').innerHTML, /View Invoice|> Edit/);
  assert.doesNotMatch(el('order-body').innerHTML, /data-action="editOrder"|data-action="confirmOrder"/);
  order.subtotal = 0; order.grandTotal = 0; order.lines = [{ kind: 'item', productId: 'itemA', quantityQty: 1000, unitPricePaise: 0, lineTotalPaise: 0, itemSnapshot: { name: 'A very long product name that must wrap without clipping', unitSymbol: 'kg' } }];
  el('order-body').listeners.click({ target: { closest: () => ({ dataset: { action: 'viewOrder', id: 'orderA' } }) } });
  assert.match(el('order-fields').innerHTML, /Subtotal/);
  assert.match(el('order-fields').innerHTML, /Total/);
  assert.match(el('order-fields').innerHTML, /A very long product name/);
  ui.setSession({ uid: 'accountA' }, { role: 'account_admin', active: true, fullName: 'Account Admin' });
  await el('order-refresh').listeners.click();
  assert.doesNotMatch(el('order-body').innerHTML, /data-action="editOrder"/);
  ui.setSession({ uid: 'adminA' }, { role: 'admin', active: true, fullName: 'Admin' });
  await el('order-refresh').listeners.click();
  assert.match(el('order-body').innerHTML, /data-action="editOrder"[^>]*>Edit/);
  assert.doesNotMatch(el('order-body').innerHTML, /Record payment request/);
  order.archivedAt = { toMillis: () => 1 };
  await el('order-refresh').listeners.click();
  assert.match(el('order-body').innerHTML, /data-action="cancelOrder"[^>]*>Cancel/);
  assert.doesNotMatch(el('order-body').innerHTML, /data-action="cancelOrder"[^>]*disabled/);
  el('order-body').listeners.click({ target: { closest: () => ({ dataset: { action: 'cancelOrder', id: 'orderA' } }) } });
  assert.match(el('order-fields').innerHTML, /archive history will remain/);
  assert.match(el('order-fields').innerHTML, /Deducted stock will be restored/);
});
